select
    2025::integer as release_year,
    2021::integer as lsoa_boundary_year,
    2024::integer as local_authority_boundary_year,
    2022::integer as population_year,
    false as is_population_excluding_prisoners,
    d.lsoa_code,
    lsoa.lsoa_name_2021 as lsoa_name,
    imd.local_authority_district_code,
    la.name as local_authority_district_name,
    d.imd_score,
    d.imd_rank,
    d.imd_decile,
    d.income_score,
    d.income_rank,
    d.income_decile,
    d.employment_score,
    d.employment_rank,
    d.employment_decile,
    d.education_skills_and_training_score,
    d.education_skills_and_training_rank,
    d.education_skills_and_training_decile,
    d.health_deprivation_and_disability_score,
    d.health_deprivation_and_disability_rank,
    d.health_deprivation_and_disability_decile,
    d.crime_score,
    d.crime_rank,
    d.crime_decile,
    d.barriers_to_housing_and_services_score,
    d.barriers_to_housing_and_services_rank,
    d.barriers_to_housing_and_services_decile,
    d.living_environment_score,
    d.living_environment_rank,
    d.living_environment_decile,
    d.idaci_score,
    d.idaci_rank,
    d.idaci_decile,
    d.idaopi_score,
    d.idaopi_rank,
    d.idaopi_decile,
    d.children_and_young_people_score,
    d.children_and_young_people_rank,
    d.children_and_young_people_decile,
    d.adult_skills_score,
    d.adult_skills_rank,
    d.adult_skills_decile,
    d.geographical_barriers_score,
    d.geographical_barriers_rank,
    d.geographical_barriers_decile,
    d.wider_barriers_score,
    d.wider_barriers_rank,
    d.wider_barriers_decile,
    d.indoors_score,
    d.indoors_rank,
    d.indoors_decile,
    d.outdoors_score,
    d.outdoors_rank,
    d.outdoors_decile,
    d.total_population,
    d.children_population,
    d.older_population,
    d.working_age_population
from {{ ref('stg_ukhfd_domains_of_deprivation_by_lsoa') }} as d
left join {{ ref('stg_ukhfd_index_of_multiple_deprivation_by_lsoa') }} as imd
    on d.release_year = imd.release_year
    and d.lsoa_code = imd.lsoa_code
left join {{ ref('stg_ukhfd_ordnance_survey_lsoa_2021') }} as lsoa
    on d.lsoa_code = lsoa.lsoa_code_2021
left join {{ ref('ons_geography') }} as la
    on imd.local_authority_district_code = la.code
where d.release_year = 2025
